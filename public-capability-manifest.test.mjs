import assert from "node:assert/strict";
import { DEMO_CAPABILITIES, PRIVATE_CAPABILITIES, capabilityAnswerNeedsScope, publicCapabilityContext, publicCapabilityRepairContext, unsupportedPublicClaim } from "./demo-src/publicCapabilityManifest.ts";

const context = publicCapabilityContext("Can you code?");
const emailContext = publicCapabilityContext("Can you read my email?");
assert.equal(DEMO_CAPABILITIES.length, 5);
assert.equal(PRIVATE_CAPABILITIES.length, 9);
assert.match(context, /suggest code as TEXT/i);
assert.match(context, /THIS DEMO CANNOT:.*edit or run code/i);
assert.match(context, /Jahaziel Code \(Verified review flow\)/i);
assert.match(context, /THIS DEMO CANNOT: read email, read a calendar/i);
assert.doesNotMatch(context, /New Outlook ingestion incomplete/i);
assert.match(emailContext, /New Outlook ingestion incomplete/i);
assert.doesNotMatch(emailContext, /Jahaziel Code \(Verified review flow\)/i);
assert.match(publicCapabilityContext("What can the actual AI do?"), /Model intelligence and Skin/i);
assert.match(context, /Ask a focused question only if needed/i);
assert.match(publicCapabilityRepairContext("Can you code?"), /suggest code as text/i);
assert.match(publicCapabilityRepairContext("Can you code?"), /Cannot run code or edit a repository/i);
assert.equal(unsupportedPublicClaim("Yes, I can read your email."), true);
assert.equal(unsupportedPublicClaim("The demo can read your email."), true);
assert.equal(unsupportedPublicClaim("You can read your email in this public demo."), true);
assert.equal(unsupportedPublicClaim("THIS PUBLIC DEMO can read your email."), true);
assert.equal(unsupportedPublicClaim("In this public demo, you can inspect projects, prepare code edits, and run checks."), true);
assert.equal(unsupportedPublicClaim("In this public demo, you can:\n1. Chat\n2. Run scripts or code\n3. Access external resources"), true);
assert.equal(unsupportedPublicClaim("I can suggest code as text here; the private JCode can run checks."), false);
assert.equal(unsupportedPublicClaim("The demo is fully functional without any limitations."), true);
assert.equal(unsupportedPublicClaim("The demo is not fully functional."), false);
assert.equal(unsupportedPublicClaim("I can't access your email here."), false);
assert.equal(unsupportedPublicClaim("The private prototype can read connected email with permission."), false);
assert.equal(capabilityAnswerNeedsScope("Can you code?", "Yes, I can write code."), true);
assert.equal(capabilityAnswerNeedsScope("Can you code?", "Yes, you can code. DEMO: Local text chat. PRIVATE: JCode."), true);
assert.equal(capabilityAnswerNeedsScope("Can you code?", "This public demo cannot code. It can suggest code as text; the private system can edit it."), true);
assert.equal(capabilityAnswerNeedsScope("Can you code?", "This public demo can suggest code as text but cannot edit a project."), true);
assert.equal(capabilityAnswerNeedsScope("Can you code?", "Here I can write code as text; private JCode can edit projects."), false);
assert.equal(capabilityAnswerNeedsScope("Can you read email?", "No, I cannot read your email."), false);
console.log("Public capability manifest and claim guard: PASS");
